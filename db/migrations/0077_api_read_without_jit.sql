-- 0077 — запросы публичного API без JIT-компиляции.
--
-- jit в кластере включён (отчёт хранилища 09.10). JIT срабатывает по оценке
-- стоимости запроса (jit_above_cost = 100 000), а не по его длительности.
-- Запросы истории и карточек обходят партиции горячего слоя и упакованную
-- историю, и их оценка легко переходит порог, хотя сами они выполняются за
-- десятки миллисекунд. Тогда к каждому такому запросу прибавляется компиляция
-- в LLVM — от сотен миллисекунд до секунды процессорного времени, и в
-- контейнере базы с одним ядром она же задерживает соседние запросы. JIT
-- окупается на долгих аналитических проходах по миллионам строк, а у API
-- таких нет: тяжёлые агрегаты считает служба аналитики под своей ролью.
--
-- Как и в 0026, настройка ставится на роль, а не на кластер: сбор, упаковщик
-- и аналитика работают как прежде. Значение действует для новых сеансов —
-- после миграции пул API нужно перезапустить.
--
-- Откат: ALTER ROLE api_read RESET jit;
ALTER ROLE api_read SET jit = off;
