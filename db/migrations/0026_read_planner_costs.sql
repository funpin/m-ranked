-- 0026 — стоимость случайного чтения для роли публичного чтения
--
-- random_page_cost по умолчанию равен 4. Это отношение для шпиндельного диска:
-- случайное чтение вчетверо дороже последовательного. Под нами виртуальный
-- диск на SSD, где разница близка к единице, и завышенная стоимость заставляла
-- планировщик избегать индексных соединений.
--
-- Чем это обошлось. Карточка вуза выполняет анти-join к
-- ingest.publication_metric_snapshot_active: у снимка не должно быть более
-- позднего исправления. Проба — снимки одного аккаунта, несколько тысяч строк.
-- При стоимости 4 планировщик выбирал Hash Anti Join и строил хеш по всем
-- 63 разделам целиком: 8 865 348 строк, около четырёх гигабайт чтения и
-- полгигабайта во временные файлы. Замер на проде 15.09.2026:
--
--   random_page_cost = 4     55 877 мс  (запрос не укладывался в
--                                        statement_timeout и отдавал 500)
--   random_page_cost = 1.1      529 мс  (Nested Loop Anti Join по индексу)
--
-- Разница в сто пять раз, причём план меняется только у соединения — сам
-- результат тот же. Отдельные карточки вузов из-за этого не открывались вовсе.
--
-- Настройка ставится на роль, а не на кластер: сбор пишет большими пачками и
-- последовательное чтение ему уместнее, а трогать его план без замеров незачем.
-- Роль применяет значение к новым сеансам, поэтому после этой миграции API
-- нужно перезапустить — иначе пул доработает на прежних соединениях.
ALTER ROLE api_read SET random_page_cost = 1.1;
