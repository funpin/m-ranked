-- 0085 — уровень аномалии поста читается без строки состояния.
--
-- «Находки» и их нормы соединяют посты с analytics.post_anomaly_state ради
-- пяти узких полей: id, дата поста, время
-- анализа, уровень и статус перепроверки. Сама строка весит ~2 КБ (признаки,
-- качество, версии детекторов, хвост), и на проде 16.10 таблица занимала
-- 441 МБ на 74 тыс. строк при 256 МБ shared_buffers. Холодный запрос
-- «Находок» дважды проходил её целиком (выдача и нормы): 1,2 с из 3,0 с,
-- 113 тыс. из 158 тыс. прочитанных страниц.
--
-- Покрывающий индекс по publication_id с этими полями — около 5 МБ; он
-- годится и для соединения по id, и для полного прохода только по индексу.
-- Карта видимости таблицы почти всегда полная (автоочистка каждые несколько
-- минут, 0061), так что в кучу такой проход не ходит.
--
-- Цена записи: обновления строки и так не HOT (next_due_at в индексе), каждое
-- уже пишет три записи индексов; эта — четвёртая, ~16 обновлений в секунду.
--
-- CONCURRENTLY и без транзакции: обычное построение держало бы запись
-- анализа и чтения API на всё время построения (см. 0061).
--
-- Если построение прервалось, остаётся нерабочий индекс, и IF NOT EXISTS его
-- не заменит: DROP INDEX CONCURRENTLY и запустить миграцию снова.
-- Откат: DROP INDEX CONCURRENTLY analytics.post_anomaly_state_level_idx;
CREATE INDEX CONCURRENTLY IF NOT EXISTS post_anomaly_state_level_idx
    ON analytics.post_anomaly_state (publication_id)
    INCLUDE (published_at, analyzed_at, level, review_status);
