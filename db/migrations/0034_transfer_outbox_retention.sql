-- 0034 — разрешить отправителю убирать подтверждённые конверты
--
-- Причина: подтверждённый конверт хранит полезную нагрузку и после доставки.
-- Метод очистки в продюсере был с самого начала, но вызывать его было некому,
-- и очередь росла примерно на 600 МиБ в сутки. На диске сервера-сборщика,
-- где рядом лежит рабочий набор данных, это две недели до отказа записи.
--
-- Очистку взяла на себя служба отправки (collector_target.transfer_sender),
-- она работает от роли outbox_worker. Миграция 0029 выдала этой роли только
-- чтение и обновление, поэтому удаление падало на правах.
--
-- Удаляются исключительно записи в состоянии acknowledged и старше окна
-- хранения: неподтверждённые данные не удаляются никогда и ни при каком
-- пороге. Окно нужно не ради места, а ради замены — если потребитель потеряет
-- данные, отдать их заново можно только пока конверт цел.
--
-- Откат: REVOKE DELETE ON ops_and_admin.transfer_outbox FROM outbox_worker;
--        очистка перестанет работать, очередь снова начнёт расти.

GRANT DELETE ON TABLE ops_and_admin.transfer_outbox TO outbox_worker;
