-- 0059 — упакованная история замеров публикаций.
--
-- Каждый замер был строкой ingest.publication_metric_snapshot: ~410 байт
-- данных и ~360 байт индексов, а разбивка реакций — ещё строками
-- ingest.reaction_breakdown. На сентябрь 2026 — 12,5 млн строк и 9,4 ГБ ради
-- 31 тыс. постов. Замеры старше двух суток больше не меняются, и строка на
-- замер им не нужна.
--
-- Горячий слой остаётся прежним: запись, триггеры, исправления, отсев
-- повторов. Упаковщик переносит замеры старше границы в одну строку на
-- публикацию — типизированные массивы со сжатием lz4 (~27 байт на замер) — и
-- удаляет их из горячих таблиц. Ничего не теряется: каждая версия каждого
-- бакета, все счётчики, качества, флаги, время сбора и записи, запуск,
-- evidence и разбивка реакций. Только в горячем слое живут технические
-- source_fingerprint, semantic_fingerprint и ingested_xid: первые два нужны
-- лишь для отсева повторов при приёме, третий — для ограждения разбивки.
--
-- Массивы элементные: точку собирает unnest … WITH ORDINALITY без оконных
-- функций, поэтому прежний SQL читает обе части через одно представление.
--   collected_at = observed_at + collected_lag мкс
--   created_at   = collected_at + created_lag мкс
--   age_seconds  = ⌊observed_at − published_at⌋ + age_residual
--   bucket       = ⌊epoch(observed_at) / 300⌋ + bucket_residual
--   codes        = качество ×5 по 3 бита, interval_uncertain (бит 15),
--                  synthetic (16), visible — последняя версия в бакете (17)
--
-- Откат: функции и представления вернуть из 0011/0012/0058, таблицу удалить
-- только после распаковки (ingest.unpack_publication_history).
